const GLYPH_W = 5;
const GLYPH_H = 7;
const GLYPH_GAP = 1;
const FALLBACK_GLYPH = ["11111", "10001", "10101", "10001", "10101", "10001", "11111"];

function measureBitmapText(text, scale = 1) {
    const s = Math.max(1, Math.round(scale));
    const str = String(text ?? "");
    if (str.length === 0) return { width: 0, height: GLYPH_H * s };

    const width = (str.length * GLYPH_W + (str.length - 1) * GLYPH_GAP) * s;
    const height = GLYPH_H * s;
    return { width, height };
}

function drawBitmapText(ctx, text, x, y, scale = 1, color = "#ffffff") {
    const s = Math.max(1, Math.round(scale));
    const startX = Math.round(x);
    const startY = Math.round(y);
    const str = String(text ?? "");

    ctx.save();
    ctx.fillStyle = color;

    for (let i = 0; i < str.length; i++) {
        const ch = str[i];
        const glyph = BITMAP_GLYPHS[ch] || BITMAP_GLYPHS[ch.toUpperCase()] || FALLBACK_GLYPH;
        const charX = startX + i * (GLYPH_W + GLYPH_GAP) * s;

        for (let row = 0; row < GLYPH_H; row++) {
            const line = glyph[row];
            for (let col = 0; col < GLYPH_W; col++) {
                if (line[col] === "1") {
                    ctx.fillRect(
                        charX + col * s,
                        startY + row * s,
                        s,
                        s
                    );
                }
            }
        }
    }

    ctx.restore();
    return measureBitmapText(str, s);
}

